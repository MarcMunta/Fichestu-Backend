    v_start := clock_timestamp();
    INSERT INTO user_badges (user_id, badge_id, awarded_at)
    SELECT u.user_id, ((u.user_id % 20) + 1), clock_timestamp() - ((u.user_id % 90) || ' days')::interval
    FROM users u
    WHERE u.user_id % 3 = 0;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load user badges', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO token_price_history (token_id, price, recorded_at)
