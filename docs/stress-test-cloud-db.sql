        ROUND((t.current_price * (0.5 + random()))::numeric, 2),
        clock_timestamp() - ((gs % 1440) || ' minutes')::interval
    FROM tokens t
    CROSS JOIN generate_series(1, v_price_points_per_token) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
