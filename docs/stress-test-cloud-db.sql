);

CREATE TABLE user_wallets (
    user_id INTEGER NOT NULL,
    token_id INTEGER NOT NULL,
    quantity NUMERIC(15, 4) NOT NULL DEFAULT 0.0000,
    PRIMARY KEY (user_id, token_id),
    CONSTRAINT fk_stress_user_wallets_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_stress_user_wallets_token FOREIGN KEY (token_id) REFERENCES tokens(token_id) ON DELETE CASCADE
