    CONSTRAINT fk_stress_match_participants_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TABLE match_cards (
    card_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER,
    owner_id INTEGER,
    card_type VARCHAR(20),
    card_value INTEGER,
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
