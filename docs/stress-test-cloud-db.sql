    v_start := clock_timestamp();
    INSERT INTO game_sessions (status, start_time, end_time, winner_id, matchmaking_deadline, ball_pick_deadline, battle_round_deadline)
    SELECT
        CASE WHEN gs % 5 = 0 THEN 'FINISHED' WHEN gs % 5 = 1 THEN 'WAITING' ELSE 'BATTLE' END,
        clock_timestamp() - ((gs % 10080) || ' minutes')::interval,
        CASE WHEN gs % 5 = 0 THEN clock_timestamp() - ((gs % 1000) || ' minutes')::interval ELSE NULL END,
        CASE WHEN gs % 5 = 0 THEN ((gs % v_user_count) + 1) ELSE NULL END,
        clock_timestamp() + '2 minutes'::interval,
        clock_timestamp() + '5 minutes'::interval,
        clock_timestamp() + '8 minutes'::interval
    FROM generate_series(1, v_session_count) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load game sessions', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO match_participants (match_id, user_id, selected_ball_number, multiplier_won, current_hp, is_alive)
    SELECT
        s.match_id,
        (((s.match_id - 1) * v_participants_per_session + p.participant_no - 1) % v_user_count) + 1,
        p.participant_no,
        ROUND((0.5 + random() * 5)::numeric, 2),
        10 + ((s.match_id + p.participant_no) % 90),
        ((s.match_id + p.participant_no) % 7) <> 0
    FROM game_sessions s
    CROSS JOIN generate_series(1, v_participants_per_session) AS p(participant_no);
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load match participants', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO match_cards (match_id, owner_id, card_type, card_value, is_used, round_number, target_user_id)
    SELECT
        s.match_id,
        (((s.match_id - 1) * v_cards_per_session + c.card_no - 1) % v_user_count) + 1,
        CASE c.card_no % 3 WHEN 0 THEN 'ATTACK' WHEN 1 THEN 'DEFENSE' ELSE 'HEAL' END,
        5 + ((s.match_id + c.card_no) % 25),
        c.card_no % 4 = 0,
