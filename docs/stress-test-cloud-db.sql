    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load users', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

