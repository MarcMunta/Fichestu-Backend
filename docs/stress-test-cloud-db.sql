        (((s.match_id - 1) * v_cards_per_session + c.card_no + 11) % v_user_count) + 1
    FROM game_sessions s
    CROSS JOIN generate_series(1, v_cards_per_session) AS c(card_no);
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load match cards', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO game_session_events (match_id, event_type, payload, created_at)
    SELECT s.match_id, 'STRESS_EVENT', '{"source":"stress-test"}', s.start_time + ((e.event_no * 10) || ' seconds')::interval
    FROM game_sessions s
    CROSS JOIN generate_series(1, 3) AS e(event_no);
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load game events', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO transactions_log (user_id, type, amount_fiat, description, created_at)
    SELECT
        u.user_id,
        CASE gs % 3 WHEN 0 THEN 'BUY' WHEN 1 THEN 'SELL' ELSE 'REWARD' END,
        ROUND((random() * 500)::numeric, 2),
        'Synthetic stress transaction',
        clock_timestamp() - ((u.user_id + gs) % 10000 || ' minutes')::interval
    FROM users u
    CROSS JOIN generate_series(1, v_transactions_per_user) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load transactions', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO notifications (user_id, title, body, type, is_read, created_at)
    SELECT
        u.user_id,
        'Stress notification ' || gs,
        'Synthetic notification body for stress testing.',
        CASE gs % 3 WHEN 0 THEN 'GAME' WHEN 1 THEN 'MARKET' ELSE 'PROFILE' END,
        gs % 2 = 0,
        clock_timestamp() - ((u.user_id + gs) % 5000 || ' minutes')::interval
    FROM users u
    CROSS JOIN generate_series(1, v_notifications_per_user) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load notifications', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO minigame_attempts (user_id, game_type, payment_type, status, entry_cost, reward_amount, score, started_at, completed_at)
    SELECT
        u.user_id,
        CASE gs % 2 WHEN 0 THEN 'MEMORY' ELSE 'REACTION' END,
        CASE gs % 2 WHEN 0 THEN 'FREE' ELSE 'TOKEN' END,
        CASE gs % 4 WHEN 0 THEN 'STARTED' ELSE 'COMPLETED' END,
        CASE gs % 2 WHEN 0 THEN 0 ELSE 1 END,
        ROUND((random() * 25)::numeric, 2),
        (random() * 10000)::integer,
