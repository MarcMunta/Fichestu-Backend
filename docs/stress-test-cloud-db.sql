        CASE WHEN gs % 4 = 0 THEN NULL ELSE clock_timestamp() - ((u.user_id + gs) % 19900 || ' minutes')::interval END
    FROM users u
    CROSS JOIN generate_series(1, v_minigame_attempts_per_user) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load minigame attempts', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    FOR v_i IN 1..v_workload_iterations LOOP
        v_start := clock_timestamp();
        UPDATE tokens
        SET current_price = ROUND((current_price * (0.95 + random() * 0.10))::numeric, 2),
            last_update = clock_timestamp();
        GET DIAGNOSTICS v_rows = ROW_COUNT;
        INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'workload update token prices #' || v_i, v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

        v_start := clock_timestamp();
        INSERT INTO token_price_history (token_id, price, recorded_at)
        SELECT token_id, current_price, clock_timestamp()
        FROM tokens;
        GET DIAGNOSTICS v_rows = ROW_COUNT;
        INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'workload append price history #' || v_i, v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

        v_start := clock_timestamp();
        UPDATE user_wallets
        SET quantity = quantity + ROUND((random() * 2 - 1)::numeric, 4)
        WHERE user_id IN (
            SELECT user_id
            FROM users
            WHERE user_id BETWEEN 1 + ((v_i - 1) * 100) AND (v_i * 1000)
        );
        GET DIAGNOSTICS v_rows = ROW_COUNT;
        INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'workload update wallet slice #' || v_i, v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);
    END LOOP;

    v_start := clock_timestamp();
    SELECT COUNT(*) INTO v_rows
    FROM (
        SELECT u.user_id, SUM(w.quantity * t.current_price) AS portfolio_value
        FROM users u
        JOIN user_wallets w ON w.user_id = u.user_id
        JOIN tokens t ON t.token_id = w.token_id
        GROUP BY u.user_id
        ORDER BY portfolio_value DESC
