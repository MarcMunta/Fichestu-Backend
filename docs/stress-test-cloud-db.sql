    FROM generate_series(1, 20) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load badges', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO tokens (name, color_code, current_price, last_update)
    SELECT
        'Stress Token ' || gs,
        '#' || lpad(to_hex((gs * 654321) % 16777215), 6, '0'),
        ROUND((1 + random() * 499)::numeric, 2),
        clock_timestamp()
    FROM generate_series(1, v_token_count) AS gs;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    INSERT INTO stress_results VALUES (DEFAULT, v_run_id, 'load tokens', v_rows, v_start, clock_timestamp(), ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - v_start))::numeric * 1000, 3), NULL);

    v_start := clock_timestamp();
    INSERT INTO users (username, email, password_hash, fiat_balance, role, created_at, preferred_language, profile_title, profile_bio, profile_page_background)
    SELECT
        'stress_user_' || gs,
        'stress_user_' || gs || '@loadtest.fichestu.local',
        'stress_hash_' || gs,
        ROUND((random() * 10000)::numeric, 2),
        CASE WHEN gs % 1000 = 0 THEN 'ADMIN' ELSE 'USER' END,
        clock_timestamp() - ((gs % 365) || ' days')::interval,
        CASE WHEN gs % 3 = 0 THEN 'en' ELSE 'es' END,
        'Stress profile ' || gs,
        'Synthetic profile generated for cloud database stress testing.',
        CASE WHEN gs % 4 = 0 THEN 'preset:aurora' ELSE 'preset:casino' END
