DO $$
DECLARE
    v_run_id TEXT := to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || txid_current();
    v_start TIMESTAMP WITH TIME ZONE;
    v_rows BIGINT;
    v_user_count INTEGER;
    v_token_count INTEGER;
    v_price_points_per_token INTEGER;
    v_session_count INTEGER;
    v_participants_per_session INTEGER;
    v_cards_per_session INTEGER;
    v_transactions_per_user INTEGER;
    v_notifications_per_user INTEGER;
    v_minigame_attempts_per_user INTEGER;
    v_workload_iterations INTEGER;
    v_i INTEGER;
    v_plan_line TEXT;
    v_line_no INTEGER;
BEGIN
    SELECT config_value INTO v_user_count FROM stress_config WHERE config_key = 'user_count';
    SELECT config_value INTO v_token_count FROM stress_config WHERE config_key = 'token_count';
    SELECT config_value INTO v_price_points_per_token FROM stress_config WHERE config_key = 'price_points_per_token';
    SELECT config_value INTO v_session_count FROM stress_config WHERE config_key = 'session_count';
    SELECT config_value INTO v_participants_per_session FROM stress_config WHERE config_key = 'participants_per_session';
    SELECT config_value INTO v_cards_per_session FROM stress_config WHERE config_key = 'cards_per_session';
    SELECT config_value INTO v_transactions_per_user FROM stress_config WHERE config_key = 'transactions_per_user';
    SELECT config_value INTO v_notifications_per_user FROM stress_config WHERE config_key = 'notifications_per_user';
    SELECT config_value INTO v_minigame_attempts_per_user FROM stress_config WHERE config_key = 'minigame_attempts_per_user';
    SELECT config_value INTO v_workload_iterations FROM stress_config WHERE config_key = 'workload_iterations';

    INSERT INTO stress_runs (run_id, config)
    SELECT v_run_id, jsonb_object_agg(config_key, config_value)
    FROM stress_config;

    v_start := clock_timestamp();
    INSERT INTO badges (name, icon_url, description)
