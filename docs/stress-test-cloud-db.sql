CREATE TABLE tokens (
    token_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    color_code VARCHAR(7),
    current_price NUMERIC(15, 2) NOT NULL DEFAULT 10.00,
