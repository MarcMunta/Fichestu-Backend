CREATE TABLE stress_runs (
    run_id TEXT PRIMARY KEY,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT clock_timestamp(),
    finished_at TIMESTAMP WITH TIME ZONE NULL,
    db_name TEXT NOT NULL DEFAULT current_database(),
    db_user TEXT NOT NULL DEFAULT current_user,
    server_version TEXT NOT NULL DEFAULT current_setting('server_version'),
    config JSONB NOT NULL
);

CREATE TABLE stress_results (
    step_order INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    step_name TEXT NOT NULL,
    rows_affected BIGINT NOT NULL DEFAULT 0,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_ms NUMERIC(14, 3) NOT NULL,
    notes TEXT NULL
);

CREATE TABLE stress_explain_lines (
    run_id TEXT NOT NULL,
    plan_name TEXT NOT NULL,
    line_no INTEGER NOT NULL,
    plan_line TEXT NOT NULL,
