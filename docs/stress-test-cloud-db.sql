/*
Fichestu cloud DB stress test and synthetic data load.

Target: PostgreSQL/Supabase.
Safety: this script uses only schema "fichestu_stress". It does not write to
public app tables. Re-run safe: it drops/recreates only fichestu_stress.

How to run with psql:
  psql "$DATABASE_URL" -f docs/stress-test-cloud-db.sql

Where results are stored:
  SELECT * FROM fichestu_stress.stress_results ORDER BY step_order;
  SELECT * FROM fichestu_stress.stress_explain_lines ORDER BY plan_name, line_no;
  SELECT * FROM fichestu_stress.stress_capacity_report ORDER BY total_bytes DESC;

Cleanup when finished:
  DROP SCHEMA IF EXISTS fichestu_stress CASCADE;
*/

DROP SCHEMA IF EXISTS fichestu_stress CASCADE;
CREATE SCHEMA fichestu_stress;

SET search_path TO fichestu_stress, public;
SET client_min_messages TO WARNING;

CREATE TABLE stress_config (
    config_key TEXT PRIMARY KEY,
    config_value INTEGER NOT NULL
);

